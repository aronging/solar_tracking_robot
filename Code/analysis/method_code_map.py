"""Method-to-code map: scan solar_tracker/ for docstring tags `NM-METHOD: <name> | STAGE: <n>`
and write docs/method_code_map.md (method, stage, file, function/class, lines, test, analysis).
"""
import ast
import re

from _common import CODE, setup

TAG = re.compile(r"^\s*NM-METHOD:\s*(.+?)\s*\|\s*STAGE:\s*(\S+)\s*$", re.M)

# module path (relative to solar_tracker/) -> (test files, analysis scripts from spec section 15)
MAP = {
    "numerics/roots.py": ("test_roots.py", "kepler_convergence.py, sunrise_roots.py"),
    "numerics/linalg.py": ("test_linalg.py", "cosine_fit_study.py"),
    "numerics/leastsq.py": ("test_leastsq.py", "fit_servo_cal.py, cosine_fit_study.py, offset_convergence.py"),
    "numerics/optimize.py": ("test_optimize.py", "golden_convergence.py"),
    "numerics/integrate.py": ("test_integrate_pid.py", "pid_study.py, tracking_gain.py"),
    "solar/position.py": ("test_solar_position.py",
                          "kepler_convergence.py, sunrise_roots.py, prediction_vs_measured.py"),
    "control/pid.py": ("test_integrate_pid.py", "pid_study.py"),
    "control/heading.py": ("test_integrate_pid.py, test_supervisor_sim.py", "pid_study.py"),
    "control/acquire.py": ("test_acquire.py, test_supervisor_sim.py", "golden_convergence.py"),
    "control/refine.py": ("test_refine.py, test_supervisor_sim.py", "cosine_fit_study.py"),
    "control/offsets.py": ("test_offsets.py, test_supervisor_sim.py", "offset_convergence.py"),
}


def main():
    args = setup(__file__, __doc__, default_out=CODE / "docs")
    pkg = CODE / "solar_tracker"
    rows = []
    for path in sorted(pkg.rglob("*.py")):
        rel = path.relative_to(pkg).as_posix()
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                continue
            for name, stage in TAG.findall(ast.get_docstring(node) or ""):
                tests, scripts = MAP.get(rel, ("-", "-"))
                rows.append((stage, rel, node.lineno, name, node.name, node.end_lineno,
                             ", ".join(f"`tests/{t}`" for t in tests.split(", ")) if tests != "-" else "-",
                             ", ".join(f"`analysis/{s}`" for s in scripts.split(", ")) if scripts != "-" else "-"))
    rows.sort()
    lines = ["# Method-to-code map", "",
             "Generated by `python analysis/method_code_map.py` from the `NM-METHOD: <name> | STAGE: <n>` "
             "docstring tags. Do not edit by hand.", "",
             "| Method | Stage | File | Function / class | Lines | Test file | Analysis script |",
             "|---|---|---|---|---|---|---|"]
    for stage, rel, start, name, obj, end, tests, scripts in rows:
        lines.append(f"| {name.replace('|', '/')} | {stage} | `solar_tracker/{rel}` | `{obj}` | "
                     f"{start}-{end} | {tests} | {scripts} |")
    out = args.out / "method_code_map.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}: {len(rows)} tagged methods in {len({r[1] for r in rows})} files")
    for stage in sorted({r[0] for r in rows}):
        print(f"  stage {stage}: {sum(r[0] == stage for r in rows)} methods")
    unmapped = sorted({r[1] for r in rows} - set(MAP))
    if unmapped:
        print(f"  WARNING: no test/analysis mapping for {unmapped}")


if __name__ == "__main__":
    main()
